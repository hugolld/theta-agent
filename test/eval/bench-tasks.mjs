// The benchmark task list (spec #136, on the #135 tracer's shape): the
// eval suite's live layer is graded task suites, and every benchmark run
// is deliberate — the suite's tasks, their prompts, their
// workspace-oracle checks, and their judge slots are checked in here,
// read by the rig's eval mode (`node test/rig/run.mjs eval <task-id>`
// for one, `--suite` for the whole list). The list is to the benchmark
// layer what test/eval/scenarios.mjs is to the replay net: the only
// source of what runs, prompt for prompt. The first suite is the four
// proposed classes (spec #136), one task each: literature triage,
// method selection, provenance recording, compute staging.
//
// Grading doctrine (GLOSSARY, "Workspace-as-oracle"): the workspace is
// the oracle — model prose proves nothing. Objective checks are
// declarative (`checks`, executed by test/eval/bench-grade.mjs against
// the task workspace the session ran in); exactly one subjective entry
// rides `models.classify()` per task, judged host-side by the named
// judge slots. Two-tier judging (spec #136): the `iteration` tier is the
// campaign-iteration judge (per-strike checks, never public-destined
// numbers); the `independent` tier — a different model family than the
// iteration judge, so judge errors cannot correlate — judges numbers
// destined for public surfaces. Both are config slots, never identities
// in code: their keys live host-side only, the judges never run in the
// rig, and at least one task (the suite's most subjective grade,
// literature triage) carries both tiers.
//
// The judge slots' history: the campaign chat provider cannot serve
// classify() (pi's classifier catalog is closed to the Jev/Clef/Decisions
// families; probed 2026-11-14, zero classifiers reachable through the
// campaign entry), so both slots name OpenRouter — the host whose key is
// configured — with different model families. The ids are the ones the
// installed pi 1.4.0 catalog actually carries and answer with (probed
// 2026-11-15: the catalog's mercury-decide endpoint is gone — 404 — and
// the span models reject the standard state shape; solar-decide and
// jev-1.13 answer).
//
// Prompts keep the capture doctrine: pure ASCII, neutral (names no
// skill and no file), one plain command per call, and the read-headroom
// phrasing shared with the scenario list. `sessions` is the
// multi-session shape: each entry is one print-mode session in the same
// task workspace; entries after the first resume with `--continue`
// (resume-keeps-tools, ADR 0007). Image input is available but not
// required: `image` names a committed asset under test/eval/assets/,
// attached through pi's @path argv — a first-prompt argument, so an
// image task is single-session. The asset is generated by the checked-in
// generator beside it, never hand-edited.

